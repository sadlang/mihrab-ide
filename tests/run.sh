#!/usr/bin/env bash
# منسّق اختبارات محراب — يشغّل الطبقات الساكنة/التطبيقيّة/الحزمة، ويرشد لطبقة الوقت.
# L0 (ساكن) + L1 (مراسي) يعملان دائمًا (بلا بناء). L2 (حزمة) يعمل إن وُجد مخرَج بناء.
# L3 (وقتيّ) يحتاج نسخة مُطلَقة بالمنفذ — يُطبَع إرشاده لا يُشغَّل هنا.
#
# الاستعمال: bash tests/run.sh          # L0+L1 (+L2 إن مبنيّ)
#            MIHRAB_L1_SOURCE=snapshot bash tests/run.sh   # فرض لقطة L1 (كـCI)
set -u
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PY="${PYTHON:-python}"
rc=0

echo "╔══════════════════ اختبارات محراب ══════════════════╗"

"$PY" "$HERE/static/lint_patchers.py" || rc=1
echo
"$PY" "$HERE/apply/check_anchors.py" || rc=1
echo
"$PY" "$HERE/bundle/check_injected.py" || rc=1
echo

# ── حارسُ الهويّة في النصّ المُصيَّر (م1) ──
# لازمٌ لا مكرَّرٌ عن L2: هذا يشهد لِقاعدة التطبيع نفسِها (ماذا يُستبدَل وماذا يُصان)
# ويعمل **بلا بناء**، بينما مِجَسّا L2 يشهدان للمخرَج ويحتاجانه.
"$PY" "$HERE/brand/check_brand.py" || rc=1
echo

# ── معجم عناوين الإعدادات: اختبارٌ سلوكيّ (يصرّف الوحدة ويستدعيها فعلًا) ──
# لازمٌ لا مكرَّر: حارسُ L0 نصّيٌّ بحت، ونصٌّ سليمُ الشكل قد يُنتج عربيّةً مكسورة.
if command -v node >/dev/null 2>&1 && [[ -f "$HERE/../.upstream/vscode/node_modules/typescript/lib/tsc.js" ]]; then
  node "$HERE/lexicon/check_lexicon.mjs" || rc=1
else
  echo "⚠️ tsc المحلّيّ غير متوفّر — تخطّي الاختبار السلوكيّ للمعجم"
fi
echo

# ── [DX-02] قياسُ رتبةِ الإكمال بالعربيّة — **قياسٌ لا حارس** ──
# يصرّف مُطابِقَ المنبع (filters.ts) ويقيس رتبةَ معرّفاتِ ص لكتاباتٍ جزئيّة. لا عتبةَ له
# (وعتبةٌ مخترَعةٌ أسوأُ من قياسٍ صادق)، ولا يُفشِل إلّا على «لا تظهر إطلاقًا» — وذاك عطبُ
# اكتشافٍ لا رأيَ فيه. يتخطّى بلطفٍ إن غابت شجرةُ المنبع أو tsc المحلّيّ.
if command -v node >/dev/null 2>&1; then
  node "$HERE/dx/completion_rank.mjs" || rc=1
fi
echo

# ── نِبراس: حارس تطابق عقد السلك (المصدر ⇄ المولَّد) ──
NEBRAS="$HERE/../extensions/mihrab-nebras"
"$PY" "$NEBRAS/contract/gen_contract.py" --check || rc=1
echo

# ── اختبارات وحدة الامتدادات (نِبراس: RPC/توافق · الترحيب: تحقّق الاسم · sad-lang: نقل LSP/محوّلات) ──
if command -v node >/dev/null 2>&1; then
  # (‏sad-lang مُدرَجٌ هنا **وفي CI** معًا منذ [DX-01]: كان مغطًّى هنا وحدَه، فبقي وصلُ
  #  تطبيع البحث بلا بوّابةٍ في التكامل المستمرّ.)
  for _ext in "$NEBRAS" "$HERE/../extensions/mihrab-welcome" "$HERE/../extensions/sad-lang"; do
    ( cd "$_ext" && node --test ) || rc=1
  done
else
  echo "⚠️ node غير متوفّر — تخطّي اختبارات وحدة الامتدادات"
fi
echo

# ── [PF-01] ميزانيّةُ الحجم — **حارسٌ** يُفشِل، وموضعُه هنا لا في L3 ──
# حتميٌّ ورخيصٌ (<10ث، بلا إطلاق) فيُبوِّب كبقيّة الطبقات. ويتخطّى **معلنًا** حين لا بناء:
# يطبع `mode=skipped` صراحةً، لأنّ حارسًا يُرجع 0 بصمتٍ حين لا يقيس شيئًا يبقى أخضرَ إلى
# الأبد — وهو الشكلُ الذي يرثه بلا انتباه من `check_injected.py`.
# (زمنُ الإقلاع **ليس هنا**: غيرُ حتميٍّ ورهنُ العتاد، وحارسٌ متذبذبٌ يُعطَّل والمعطَّلُ
#  أسوأُ من الغائب. يُشغَّل يدويًّا — انظر إرشادَ L3 أدناه.)
if command -v node >/dev/null 2>&1; then
  node "$HERE/perf/size.mjs" || rc=1
else
  echo "⚠️ node غير متوفّر — تخطّي ميزانيّة الحجم"
fi
echo

# ── [PF-02] ثراءُ العيّنة — حارسٌ يُفشِل، وموضعُه هنا ──
# يشغّل اختباراتِ الوحدة تحت مِجَسٍّ يرصد كلَّ تعبيرٍ نمطيٍّ **طُبِّق ولم يُطابِق قطّ** —
# أي فئةَ مُدخَلاتٍ يعالجها الكودُ صراحةً ولا تحويها العيّنات. وهو الشكلُ الذي نجا منه
# عطبُ `escapeSrc`: تأكيدٌ **صحيحٌ** فوق عيّنةٍ فقيرة، وكلُّ تأكيداتِ المستودع مشروطةٌ بها.
if command -v node >/dev/null 2>&1; then
  node "$HERE/meta/richness.mjs" || rc=1
else
  echo "⚠️ node غير متوفّر — تخطّي ثراء العيّنة"
fi
echo

echo "─── L3 (وقتيّ) — مساران ───"
echo "  (ج) حارسُ الحرّاس [PF-03] — عطبٌ مزروعٌ لكلّ حارس، وكلٌّ يجب أن يحمرّ **وللسبب الصحيح**:"
echo "      node tests/meta/mutation.mjs"
echo "      (‏خارجَ المسار السريع عمدًا: يشغّل كلَّ حارسٍ مرّتين. وحارسٌ بطيءٌ يُعطَّل،"
echo "       والمعطَّلُ أسوأُ من الغائب. وقاعدةُ التغطية فيه تُفشِل على حارسٍ بلا مُصابٍ وبلا إعلان.)"
echo
echo "  (أ) تشغيل حيّ مؤتمَت (يُصرِّف ويُطلق ويلتقط بنفسه — لا حاجة لإطلاق يدويّ):"
echo "      python build/dev_sync.py                       # زامِن الطبقتين 2/3 مع شجرة المنبع"
echo "      node tests/runtime/launch.mjs --build --spec   # صرِّف + أطلق + شغّل التأكيدات"
echo "      node tests/runtime/launch.mjs --folder . --tabs <ملفّ> --spec   # تشغيلة المحرّر"
echo "      node tests/runtime/launch.mjs --welcome --spec                 # تشغيلة الترحيب"
echo "        (تشغيلتان لا واحدة: صفحة الترحيب والمحرّر لا يكونان نشطين معًا في مجموعة"
echo "         تبويبات واحدة، ومحراب لا يفتح الترحيب أصلًا حين يُمرَّر ملفّ.)"
echo "        (‏--folder لازم لمِجَسّات القاعدة 22: مثلّث الشجرة وأدلّتها وأسهم اللوحات)"
echo "      node tests/runtime/launch.mjs --shot welcome --keep   # لقطة وأبقِ النسخة مفتوحة"
echo "      node tests/runtime/unicode_guard.live.mjs             # [AR-04] على الحزمة المشحونة"
echo "        (يُطلق بملفّ تعريفٍ معزول — إعداداتُك لا تُمسّ. أمسك نجاحًا كاذبًا لم تره الوحدة.)"
echo "      node tests/runtime/m6.live.mjs                        # [VA-04]+[VA-05]+[BS-04] + عتبةُ القوائم"
echo "        (حجمُ الخطّ كما يُصيَّر، وورقةُ الهويّة كما تُطبَّق، ورحلةُ النسخ للمشاركة ذهابًا"
echo "         وإيابًا — بما فيها أنّ ما نُسِخ من محرابٍ لا يُشخَّص خطأً حين يُلصَق فيه.)"
echo "      node tests/runtime/walkthrough_dir.live.mjs          # [م-١٦] اتّجاه لوح شرح الجولة"
echo "        (لوحُ الشرح مستندُ webview مستقلّ لا تعبره ورقةُ أنماطنا — يُقاس من داخل"
echo "         الإطار: اتّجاهُه مشتقٌّ من المضيف، والفجوةُ منطقيّةٌ لا فيزيائيّة.)"
echo "      node tests/runtime/scm_input.live.mjs                # [SC-01]+[SC-02] صندوقُ الالتزام ومحرّرُ الدمج"
echo "        (يبني مستودعَ git زائلًا بتعارضٍ حقيقيّ — الصندوقُ لا يقرأ خدمةَ الإعدادات،"
echo "         واللوحاتُ الثلاثُ يُحكَم على ترتيبها بالاسم لا بموضع العقدة في DOM.)"
echo "      node tests/runtime/word_boundaries.live.mjs          # [IN-01] حدُّ الكلمة العربيّة"
echo "        (شاهدُ تفعيلٍ **موجبٌ** يسبق كلَّ تأكيدٍ سالب: تأكيداتُ هذا الباب كلُّها"
echo "         «لم يُشقّ المُعرِّف» وتنجح والقيمةُ لم تصل المحرّرَ أصلًا.)"
echo "      node tests/runtime/debug_panes.live.mjs              # [DG-01]+[DG-02] لوحاتُ التنقيح ووحدةُ التصحيح"
echo "        (يوقف جلسةً حيّةً على debugger؛ ويقيس موضعَ «=» بين الاسم والقيمة، ويحقن"
echo "         نصَّ القاعدة 38 **من الملفّ** ليثبت أنّ محدِّداتِها تُطابِق فعلًا.)"
echo "      node tests/runtime/print_export.live.mjs           # [PR-01] الخطُّ المُضمَّن عند الطباعة"
echo "        (يطبع ذراعين إلى PDF بمتصفّحٍ حقيقيّ: بالقاعدة وبحذفها. تسعةَ عشرَ تأكيدًا"
echo "         وحدويًّا كانت خضراءَ والخطُّ يُضمَّن ولا يُستعمَل — «code» تحمل من ورقة"
echo "         الوكيل font-family تغلب الوراثة. والذراعُ الضابطةُ **يجب أن تسقط**، وإلّا"
echo "         فالمِسطرةُ لا تميّز ولا يُقرأ التأكيدُ السالبُ بعدها.)"
echo "      node tests/runtime/wrapping_strategy.live.mjs        # [IN-02/أ] مِسطرةُ الالتفاف simple ⇄ advanced"
echo "        (ذراعان في **العمليّة نفسِها** وتشغيلٌ متداخلٌ ABAB — التكتيلُ يُسنِد الانجرافَ"
echo "         الحراريَّ كلَّه للذراع الثانية. والشاهدُ حبرٌ لا رقمٌ مشتقّ: أينَ ينكسر السطرُ"
echo "         الأوّل فعلًا. وارتفاعُ .lines-content **لا يصلح** شاهدًا: ثابتٌ 2^24 دائمًا.)"
echo "      node tests/perf/startup.mjs                          # [PF-01] زمنُ الإقلاع — قياسٌ لا حارس"
echo "        (يستعمل آليّةَ المنبع نفسَها --prof-duration-markers فيبدأ من timeOrigin"
echo "         الحقيقيّ ويُنهي التطبيقَ ذاتيًّا. وسيطٌ لا متوسّط، وتُهمَل تشغيلتا إحماءٍ"
echo "         مقيستان (+64% ثمّ +22%). لا عتبةَ له: عتبةُ زمنٍ مطلقةٌ على عتادٍ مختلفٍ"
echo "         تُخفق دائمًا أو لا تُخفق أبدًا. للمقارنة على الجهاز نفسِه:"
echo "         node tests/perf/startup.mjs --label before   ثمّ  --label after  ثمّ  --compare before after)"
echo "  (ب) نسخة مُطلَقة يدويًّا (كما كان):"
echo "      Mihrab.exe --remote-debugging-port=9222 --remote-allow-origins=* \\"
echo "        tests/runtime/fixtures/rtl_fixture.ص"
echo "      node tests/runtime/run.mjs"
echo

if [[ $rc -eq 0 ]]; then echo "╚═══ ✅ الطبقات غير الوقتيّة نجحت ═══╝"; else echo "╚═══ ❌ فشل — راجع أعلاه ═══╝"; fi
exit $rc
