/*---------------------------------------------------------------------------------------------
 *  محراب — اسمُ مجلّد إعدادات المشروع (مصدرُ حقيقةٍ واحد).
 *--------------------------------------------------------------------------------------------*/

/**
 * ## لماذا هذا الملفّ موجود
 *
 * المنبع يُثبِّت `'.vscode'` سلسلةً حرفيّة في ٣١ موضعًا موزّعة على ٢٠ ملفًّا (المهامّ،
 * التنقيح، MCP، القصاصات، توصيات الامتدادات، الترميز، القياس…). فلا يكفي تبديلُ ثابتٍ
 * واحد: لو قرأ **مُوفِّرُ الإعدادات** من `.محراب` بينما ظلّت «تهيئةُ التنقيح» تكتب في
 * `.vscode`، صار المحرّرُ **يكتب حيث لا يقرأ** — وهو عطبٌ أسوأ من عدم النقل أصلًا،
 * لأنّه صامت: يحفظ المستخدمُ تهيئةً فلا يراها المحرّرُ ولا يخبره أحدٌ بالسبب.
 *
 * فالأسماءُ كلُّها تُشتقّ من هنا وحده. وهو في `vs/base/common` لا في طبقة workbench
 * لأنّ من مستهلكيه ما هو في طبقة `vs/platform` (التشخيص، أذونات الجلسة)، وقواعدُ
 * الطبقات في المنبع تمنع platform من استيراد workbench.
 *
 * ## لماذا ثلاثةُ أسماء لا اسمٌ واحد
 *
 * - `.محراب` — الاسمُ المعتمَد. ما يُكتَب في مشروعٍ جديد.
 * - `.mihrab` — بديلٌ لاتينيّ يُقرَأ ولا يُكتَب. لمن تمرّ مشاريعُهم على أدواتٍ أو
 *   أنظمة ملفّاتٍ لا تُطيق أسماءً عربيّة في المسارات.
 * - `.vscode` — توافقٌ خلفيّ. كلُّ مستودعٍ قائمٍ في العالم يستعمله، ومنعُ قراءته يكسر
 *   كلَّ مشروعٍ يُفتَح لا مشاريعَ محراب وحدها.
 *
 * الترتيب أدناه **من الأدنى أسبقيّةً إلى الأعلى** — وهو ترتيبُ الدمج نفسُه في
 * `ConfigurationModel.merge` (الأخيرُ يغلب). فإن وُجد المجلّدان معًا: الجديدُ يسود
 * **مفتاحًا مفتاحًا**، وما لا يذكره الجديدُ يُقرَأ من القديم. ولا يضيع إعدادٌ صامتًا.
 */

/** الاسمُ المعتمَد: ما يُكتَب فيه دائمًا. */
export const MIHRAB_CONFIG_FOLDER_NAME = '.محراب';

/** بديلٌ لاتينيّ يُقرَأ ولا يُكتَب فيه. */
export const MIHRAB_CONFIG_FOLDER_NAME_ASCII = '.mihrab';

/** اسمُ المنبع — يُقرَأ للتوافق الخلفيّ ولا يُكتَب فيه. */
export const LEGACY_CONFIG_FOLDER_NAME = '.vscode';

/**
 * كلُّ الأسماء المقروءة **من الأدنى أسبقيّةً إلى الأعلى**.
 * لا تعكس هذا الترتيب: هو حرفيًّا ترتيبُ الدمج، وعكسُه يجعل `.vscode` يغلب `.محراب`.
 */
export const CONFIG_FOLDER_NAMES_BY_PRECEDENCE: readonly string[] = [
	LEGACY_CONFIG_FOLDER_NAME,
	MIHRAB_CONFIG_FOLDER_NAME_ASCII,
	MIHRAB_CONFIG_FOLDER_NAME,
];

/** الأسماءُ كلُّها بترتيب البحث (الأعلى أسبقيّةً أوّلًا) — للاستكشاف لا للدمج. */
export const CONFIG_FOLDER_NAMES_BY_PREFERENCE: readonly string[] =
	[...CONFIG_FOLDER_NAMES_BY_PRECEDENCE].reverse();

/**
 * نمطُ glob يطابق الأسماءَ الثلاثة.
 * يُستعمل حيث كان المنبع يكتب `**\/.vscode/*.json` حرفيًّا: قاعدةُ أمانٍ تطابق
 * القديمَ وحده تصير ثقبًا في اللحظة التي يُسمّى فيها المجلّدُ باسمه الجديد.
 */
export function configFolderGlobAlternation(): string {
	return `{${CONFIG_FOLDER_NAMES_BY_PREFERENCE.join(',')}}`;
}

/** هل هذا الاسمُ مجلّدَ إعداداتِ مشروعٍ بأيّ من صيغه؟ */
export function isConfigFolderName(name: string): boolean {
	return CONFIG_FOLDER_NAMES_BY_PRECEDENCE.indexOf(name) !== -1;
}
