/**
 * تطبيعُ البحث العربيّ [DX-01] — وحدةٌ نقيّةٌ بلا `vscode`، مصدرُ حقيقةٍ واحد.
 *
 * **لماذا؟** الكاتبُ العربيُّ لا يفرّق حين يبحث بين «ا» و«أ» و«إ»، ولا يكتب التشكيلَ الذي
 * كتبه في التعليق، و«مكتبه/مكتبة» و«على/علي» تبادلٌ يوميّ. فيبحث عن دالّةٍ يعرف أنّها
 * موجودة فلا يجدها، **فيستنتج أنّ البحثَ معطوب** — والبحثُ سليمٌ والتطبيعُ ناقص.
 *
 * والمبدأُ مثبَتٌ عندنا في `patches/core/mihrabSettingsLexicon.ts` (يجرّد التشكيلَ والتطويلَ
 * لتطبيع بحث الإعدادات) — وهذه الوحدةُ **تعميمُه** على أسطحِنا كلِّها، بالطبقة الأولى.
 *
 * ⚠️ **لا تحفظ الإزاحات:** التطبيعُ يحذف محارف (تشكيلٌ وتطويلٌ وعلاماتُ اتّجاه) و**يزيد**
 * أخرى (‏NFKC يفكّ «ﻻ» إلى حرفين)، فطولُ الناتج قد يقلّ وقد يزيد. صالحٌ للمطابقة والفرز
 * والترشيح — **لا** لاشتقاق مدياتٍ في المستند. من احتاج مديات فليطابق على الأصل.
 *
 * ⚠️ **ليس أمنًا:** التطبيعُ يوحّد شكلَين مختلفَين قصدًا، فلا يُستعمَل في مقارنةِ هويّةٍ
 * (اسمُ ملفّ، مسارٌ، رمزٌ مميِّز) — هناك المطلوبُ كشفُ الانتحال لا توحيدُه ‏[BS-03].
 */

// ── الحذف: تشكيلٌ وتطويلٌ وعلاماتُ اتّجاه ─────────────────────────────────────────────
// **كلُّ نطاقٍ هنا بترميز \u صريح — لا محرفَ خفيًّا داخل تعبيرٍ نمطيّ.** القاعدةُ التي
// يتّبعها `INVALID_NAME_RE` في `extension.js`، ولها هنا سببٌ مضاعف: هذه الوحدةُ بالذات
// تتعامل مع المحارف الخفيّة، فمحرفٌ خفيٌّ مكتوبٌ حرفيًّا داخل صنفٍ نمطيٍّ لا يراه المراجع
// ولا يمسكه `diff`. (النثرُ العربيُّ في التعليقات يبقى على عرف المستودع: علامةُ يمينٍ
// مفردةٌ قبل اللاتينيّة لعزلها — مرئيّةُ الأثر، معروفةُ الموضع، وليست داخلَ منطق.)
//
// التشكيل: U+064B–U+0652 (فتحتان… سكون) · U+0653–U+0655 (مدّة، همزة فوق/تحت) ·
// U+0656–U+065F و U+0670 (ألف خنجريّة) · U+06D6–U+06ED (علاماتُ الوقف القرآنيّة).
const TASHKEEL_RE = /[\u064B-\u065F\u0670\u06D6-\u06ED]/g;
// التطويل (الكشيدة U+0640): زخرفةٌ بصريّةٌ لا معنى لها في المطابقة.
const TATWEEL_RE = /\u0640/g;
// علاماتُ الاتّجاه المفردة والعزل وفواصلُ الوصل: **شرعيّةٌ تمامًا** في نصٍّ عربيّ (٣١٢ منها
// في نواة نهلة) لكنّها غيرُ مرئيّةٍ فتكسر المطابقةَ بلا سببٍ يراه المستخدم. تُجرَّد **للبحث
// وحدَه**؛ أمّا في التشخيص فتُميَّز ولا تُمحى ‏[BS-01].
// U+200B مسافةٌ صفريّة · U+200C/U+200D فاصلا الوصل · U+200E/U+200F علامتا الاتّجاه ·
// U+061C علامةُ العربيّة · U+202A–U+202E تضمين/تجاوز · U+2066–U+2069 عزل.
const BIDI_MARKS_RE = /[\u061C\u200B-\u200F\u202A-\u202E\u2066-\u2069]/g;

// ── التوحيد: عائلاتُ الرسم التي يتبادلها الكاتب ─────────────────────────────────────
// خريطةٌ صريحةٌ محرفًا محرفًا (أوضحُ من نطاقاتٍ، وتُراجَع بالعين). المحارفُ هنا **مرئيّة**
// عمدًا: قارئُ العربيّة يراجعها بعينه، بخلاف نطاقات الخفيّ أعلاه.
const FOLD = new Map([
  // عائلةُ الألف — أشيعُ تبادلٍ في العربيّة المكتوبة.
  ["أ", "ا"],
  ["إ", "ا"],
  ["آ", "ا"],
  ["ٱ", "ا"], // ألف الوصل
  ["ٲ", "ا"],
  ["ٳ", "ا"],
  ["ٵ", "ا"],
  // التاء المربوطة ⇄ الهاء — «مكتبة/مكتبه».
  ["ة", "ه"],
  // الألف المقصورة ⇄ الياء — «على/علي».
  ["ى", "ي"],
  ["ی", "ي"], // ياء فارسيّة
  ["ے", "ي"],
  // حاملا الهمزة — «مسؤول/مسئول».
  ["ؤ", "و"],
  ["ئ", "ي"],
  // صورُ الهاء (أردو/فارسيّ) ⇐ الهاء العربيّة.
  ["ہ", "ه"],
  ["ە", "ه"],
  ["ھ", "ه"],
  ["ۃ", "ه"], // تاءٌ مربوطةٌ بنقطتين علويّتين (أردو)
  // الكاف والياء الفارسيّة/الأردويّة ⇐ نظائرها العربيّة.
  ["ک", "ك"],
  ["ڪ", "ك"],
  ["ۍ", "ي"],
]);

// أرقامُ العربيّة-الهنديّة (٠-٩) والفارسيّة (۰-۹) ⇐ الأرقامُ اللاتينيّة، فيجد مَن كتب «١٢»
// ما كُتِب «12» والعكس. (اختيارُ **نظام** الترقيم للعرض شأنٌ آخر تمامًا — راجع TY-06.)
const AR_INDIC_ZERO = 0x0660;
const EXT_ARABIC_ZERO = 0x06f0;
const ASCII_ZERO = 0x30;

/**
 * الصورةُ المطبَّعة لسلسلةٍ: بلا تشكيلٍ ولا تطويلٍ ولا علاماتِ اتّجاه، بعائلاتِ رسمٍ موحَّدة،
 * وبأرقامٍ لاتينيّة، وبلاتينيّةٍ صغيرة. **دالّةٌ نقيّة** — لا حالةَ ولا آثارَ جانبيّة.
 * @param {string} s
 * @returns {string}
 */
function normalizeArabic(s) {
  if (typeof s !== "string" || s.length === 0) return "";
  // (٠) **صيغُ العرض العربيّة أوّلًا** (‏NFKC): كتلتا U+FB50–FDFF وU+FE70–FEFF تحملان
  // صورَ الحرف حسب موضعه («ﺍ ﺎ ﺑ ﺒ») واللامألفَ المركّبة («ﻻ»). وهذه ليست حالةً نادرة:
  // هي أشيعُ ما يُلصَق من PDF ومن صفحاتٍ عربيّةٍ قديمة. فبلا هذه الخطوة يبحث المستخدمُ
  // **بما لصقه بيده** فلا يجد — وهو عينُ عطب الاكتشاف الذي وُجدت هذه الوحدةُ لعلاجه.
  // وNFKC يحلّ الكتلتين واللامألفَ دفعةً واحدة، بمعيارٍ لا بخريطةٍ نكتبها ونُغفِل منها.
  const canonical = s.normalize("NFKC");
  // (١) الحذف: يقلّص الطولَ فيسرّع ما بعده، ولا يغيّر نتيجةَ التوحيد.
  const stripped = canonical
    .replace(TASHKEEL_RE, "")
    .replace(TATWEEL_RE, "")
    .replace(BIDI_MARKS_RE, "");
  // (٢) التوحيد محرفًا محرفًا (خريطةٌ صريحة) + الأرقام.
  let out = "";
  for (const ch of stripped) {
    const folded = FOLD.get(ch);
    if (folded !== undefined) {
      out += folded;
      continue;
    }
    const cp = ch.codePointAt(0);
    if (cp >= AR_INDIC_ZERO && cp <= AR_INDIC_ZERO + 9) {
      out += String.fromCharCode(ASCII_ZERO + (cp - AR_INDIC_ZERO));
    } else if (cp >= EXT_ARABIC_ZERO && cp <= EXT_ARABIC_ZERO + 9) {
      out += String.fromCharCode(ASCII_ZERO + (cp - EXT_ARABIC_ZERO));
    } else {
      out += ch;
    }
  }
  // (٣) اللاتينيّةُ صغيرةً: معرّفاتُ ص تخلط عربيّةً ولاتينيّة، والمستخدمُ لا يراعي الحالة.
  return out.toLowerCase();
}

/**
 * هل يظهر `query` داخل `text` بعد تطبيع الطرفين؟ مطابقةُ **احتواءٍ** لا ضبابيّة: هذه
 * الوحدةُ تصحّح الرسمَ ولا تنافس مُطابِقَ Monaco الضبابيّ. استعلامٌ فارغٌ يطابق كلَّ شيء.
 * @param {string} query @param {string} text @returns {boolean}
 */
function matchesNormalized(query, text) {
  const q = normalizeArabic(query);
  if (!q) return true;
  return normalizeArabic(text).includes(q);
}

/**
 * نصُّ ترشيحٍ يطابق **الرسمَين معًا**: الأصلَ والمطبَّع، مفصولَين بمسافة.
 *
 * هذه هي الحيلةُ التي تجعل التطبيعَ ينفع داخل مُرشِّح Monaco رغم أنّنا **لا نملك تطبيعَ
 * ما يكتبه المستخدم** هناك: `CompletionItem.filterText` هو ما يُطابَق عليه (لا `label`
 * الذي يُعرَض)، فحملُه للرسمَين يجعل «الفضة» تجد ما كُتِب «الفضه» والعكس — بلا رقعةِ نواة
 * ولا مسٍّ بالمنبع. وإن تطابق الرسمان أُعيد الأصلُ وحدَه (لا تكرارَ بلا فائدة).
 *
 * **حدٌّ معلَن:** هذا يصلح الرسمَ ولا يصلح **الرتبة**؛ فمطابقةٌ في الشقّ المطبَّع تأتي بعد
 * مطابقةٍ في الأصل. قياسُ الرتبة بندٌ مستقلّ ‏[DX-02].
 * @param {string} label @returns {string}
 */
function dualFilterText(label) {
  const s = String(label == null ? "" : label);
  const n = normalizeArabic(s);
  return n && n !== s.toLowerCase() ? s + " " + n : s;
}

module.exports = {
  normalizeArabic,
  matchesNormalized,
  dualFilterText,
  TASHKEEL_RE,
  TATWEEL_RE,
  BIDI_MARKS_RE,
  FOLD,
};
