"use strict";
/**
 * قالبُ رسالةِ الخطأ العربيّة وعزلُ رموزها [DX-04] — **في النصّ لا في الورقة**.
 *
 * ## لماذا في النصّ
 * رسالةُ الخطأ نصٌّ يصل إلى ثلاثةِ أسطحٍ **لا تبلغها CSS**: `aria-label` لقارئ الشاشة،
 * والحافظةُ حين يُنسَخ البلاغ، ولوحةُ المشاكل. فالعزلُ الاتّجاهيُّ إن وُضع في ورقةِ أنماطٍ
 * صحّ في الشاشة وحدها وانكسر في الثلاثة. وقد تعلّمناه مرّةً ودفعنا ثمنَه:
 * ‏`mihrabSettingsLexicon.ts` يضع `FSI…PDI` في السلسلة للسبب نفسِه.
 *
 * ## القياسُ الذي أوجبه
 * الجردُ سجّل عطبَ مزجٍ **مقيسًا** في هذا السطح بالذات: `error [SYN001]: <source>:19:1`
 * يُعاد ترتيبُه في لوحة المشاكل، و«١ من ١٠» صارت «١ ١٠ من». والسببُ قاعديّ في UAX #9:
 * الرمزُ اللاتينيُّ والرقمُ والنقطتان محايداتٌ وأرقامٌ تلتحق بالمحيط لا بمصدرها.
 *
 * ## ولماذا الآن قبل الجسر
 * مصدرُ الرسالة هو المصرِّف. فبعد أن يقوم جسرُ التشخيصات يصير كلُّ تغييرٍ في الصياغة
 * **تغييرًا في عقدٍ مع فريق اللغة**. فالقالبُ يُصاغ ويُختبَر قبل أن يصير عقدًا — وهذه
 * الوحدةُ هي الصياغةُ التنفيذيّة لِما وُثِّق في [قرارات الطباعة §٦].
 *
 * ## ما تُقرِّره هذه الوحدة وما لا تُقرِّره
 * تُقرِّر: **الترتيبَ** (ما وقع · أين · لماذا · ما العمل) و**العزلَ**. ولا تُقرِّر نصَّ
 * السبب ولا نصَّ العلاج — هما من المصرِّف، وأيُّ اختراعٍ لهما هنا كذبٌ على المستخدم.
 * فالحقولُ الغائبةُ تُحذَف ولا تُملأ بعبارةٍ عامّة.
 *
 * لا `vscode` هنا: وحدةٌ نقيّةٌ قابلةٌ للاختبار وحدويًّا.
 */

/** عزلٌ أوّلُ محرفٍ قويٍّ يحدّد اتّجاهَه (‏UAX #9). */
const FSI = "⁨";
/** مُنهي العزل. */
const PDI = "⁩";

/**
 * ‏**FSI لا LRI**: الأخير يفرض LTR على ما بداخله، فلو حمل الرمزُ يومًا حرفًا عربيًّا
 * (وأسماءُ رموزِ ص عربيّةٌ محتمَلة) قُلِب قسرًا. و`FSI` يشتقّ الاتّجاهَ من المحتوى نفسِه،
 * فيصحّ في الحالين. وهو الاصطلاح نفسُه المتّبَع في `clipboard-safety` و`bidi-guard`.
 */
function isolate(text) {
  const s = text == null ? "" : String(text);
  if (!s) return "";
  // لا نعزل ما هو معزولٌ سلفًا: تكرارُ العزل يضاعف المحارفَ في نصٍّ يُنسَخ ويُقارَن.
  if (s.startsWith(FSI) && s.endsWith(PDI)) return s;
  return FSI + s + PDI;
}

/** ينزع العزلَ — لازمٌ للمقارنة والاختبار ولأيّ مستهلكٍ يريد النصَّ الخام. */
function stripIsolates(text) {
  return text == null ? "" : String(text).split(FSI).join("").split(PDI).join("");
}

/**
 * موضعٌ مقروءٌ عربيًّا ومعزول: «الملفّ:السطر:العمود» كتلةٌ لاتينيّةٌ-رقميّةٌ واحدة.
 * السطرُ والعمودُ **بأساس ١** كما يراهما المستخدم لا كما يخزّنهما المحرّر.
 * @param {{file?:string, line?:number, column?:number}} at
 */
function formatLocation(at) {
  if (!at) return "";
  const parts = [];
  if (at.file) parts.push(String(at.file));
  if (Number.isFinite(at.line)) parts.push(String(at.line));
  if (Number.isFinite(at.column)) parts.push(String(at.column));
  if (!parts.length) return "";
  // العزلُ على الكتلة كلِّها لا على كلّ جزءٍ منها: النقطتان بين الرقمين محايدتان،
  // وعزلُ الأجزاء فرادى يترك المحايدَ بينها عاريًا فيقفز — وهو العطبُ نفسُه بصورةٍ أدقّ.
  return isolate(parts.join(":"));
}

/** الحقولُ بالترتيب المقرَّر — مصدرُ حقيقةٍ واحدٌ يقرؤه القالبُ والحارس. */
const FIELDS = ["what", "where", "why", "fix"];

const LABELS = {
  where: "الموضع",
  why: "السبب",
  fix: "ما العمل",
};

/**
 * يبني الرسالةَ على القالب الثابت: **ما وقع · أين · لماذا · ما العمل**.
 *
 * @param {object} d
 * @param {string} d.what ما وقع — الجملةُ الرئيسة (من المصرِّف).
 * @param {string} [d.code] رمزُ الخطأ (‏SYN001…) — يُعزَل ويُلحَق بالجملة الأولى.
 * @param {{file?:string, line?:number, column?:number}} [d.at] الموضع.
 * @param {string} [d.why] السبب.
 * @param {string} [d.fix] ما العمل.
 * @returns {string} نصٌّ متعدّدُ الأسطر، رمزُه وموضعُه معزولان.
 */
function formatDiagnostic(d) {
  const src = d || {};
  const what = (src.what == null ? "" : String(src.what)).trim();
  const lines = [];
  // الرمزُ **لاحقٌ بين قوسين** لا بادئةٌ: البادئةُ اللاتينيّةُ في أوّل فقرةٍ عربيّةٍ تجعل
  // المحايداتِ الطرفيّةَ تلتحق بها، وهو المسارُ الذي أنتج «error [SYN001]: …» مقلوبًا.
  const code = src.code ? ` (${isolate(src.code)})` : "";
  if (what) lines.push(what + code);
  else if (code) lines.push(code.trim());

  const where = formatLocation(src.at);
  if (where) lines.push(`${LABELS.where}: ${where}`);

  // **الغائبُ يُحذَف لا يُملأ**: جملةٌ عامّةٌ مكانَ سببٍ مجهولٍ تُعلّم المستخدمَ تجاهُلَ الحقل.
  const why = (src.why == null ? "" : String(src.why)).trim();
  if (why) lines.push(`${LABELS.why}: ${why}`);

  const fix = (src.fix == null ? "" : String(src.fix)).trim();
  if (fix) lines.push(`${LABELS.fix}: ${fix}`);

  return lines.join("\n");
}

/**
 * رمزُ خطأٍ: حرفان لاتينيّان فأكثر يليهما ثلاثةُ أرقامٍ فأكثر (‏SYN001، TYP1042).
 * **مقيَّدٌ عمدًا**: نمطٌ أوسعُ يبتلع كلماتٍ إنجليزيّةً عاديّةً في رسالةٍ مختلطة.
 */
const CODE_RE = /\b[A-Z]{2,}[0-9]{3,}\b/g;
/**
 * موضعٌ مضمَّن: `اسم:سطر:عمود` أو `اسم:سطر`. الاسمُ أيُّ شيءٍ ليس فيه مسافةٌ ولا نقطتان،
 * وقد يكون عربيًّا (‏`مثال.ص:19:1`) — وهو الشكلُ الذي يكتبه مصرِّفُ ص.
 */
const LOC_RE = /\S+:[0-9]+(?::[0-9]+)?/g;

/**
 * يعزل ما **تسرّب** من رمزٍ أو موضعٍ داخل جملةٍ جاهزة — للرسائل التي تصلنا مبنيّةً من
 * المصرِّف فلا نملك إعادةَ تركيبها بالقالب.
 *
 * هذا هو العلاجُ المباشر للعطب المقيس في الجرد: `error [SYN001]: <source>:19:1` كان
 * يُعاد ترتيبُه في لوحة المشاكل لأنّ النقطتين والأقواسَ محايداتٌ تلتحق بالمحيط العربيّ.
 *
 * **الترتيبُ مقصود**: الموضعُ أوّلًا ثمّ الرمز. لو عُزِل الرمزُ أوّلًا لَحوى محارفَ العزل،
 * فما عاد `\S+` في نمط الموضع يقف عند حدِّه الصحيح.
 */
function isolateEmbeddedRefs(text) {
  const s = text == null ? "" : String(text);
  if (!s) return "";
  // لا نلمس نصًّا فيه عزلٌ سلفًا: مصدرٌ يعزل بنفسه أدرى بحدوده منّا.
  if (s.includes(FSI)) return s;
  return s.replace(LOC_RE, m => isolate(m)).replace(CODE_RE, m => isolate(m));
}

module.exports = {
  FSI,
  PDI,
  FIELDS,
  LABELS,
  CODE_RE,
  LOC_RE,
  isolate,
  stripIsolates,
  formatLocation,
  formatDiagnostic,
  isolateEmbeddedRefs,
};
