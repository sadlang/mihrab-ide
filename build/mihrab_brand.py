#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""تطبيعُ الهويّة في النصّ المُصيَّر — مصدرُ حقيقةٍ واحدٌ لاسم المنتج (م1، الطبقة 2).

## العطبُ الذي أوجب هذه الوحدة

الهويّةُ في محراب مضبوطةٌ في `product.json` (‏nameLong=«محراب») ومحروسةٌ في build.sh.
لكنّ **النصَّ المترجَم** طبقةٌ أخرى لا يبلغها ذلك الحرس: حزمةُ اللغة المنبعيّة تُرجمت
لـVSCodium، وملفُّنا التكميليّ كُتب على منوالها، فبقي اسمُ المنبع داخلَ الجُمَل العربيّة:

    «يتحكّم فيما إذا كان يُفعَّل جعل VSCodium محرّر Git…»
    «افتراضيًّا، يُطلق VSCodium إكمال قيمة الخاصّيّة…»

فالمستخدم يقرأ عربيّةً صحيحةً تسمّي له برنامجًا آخر. وهذا عطبُ هويّةٍ من صنف
‏`updateUrl` نفسِه (الذي كان يستبدل محرابًا بالمنبع صامتًا): الاسمُ يتسرّب من مكانٍ
لا يفحصه أحد.

## لماذا وحدةٌ مشتركة لا استبدالٌ في كلّ سكربت

الاسمُ يُكتب في ثلاثة مسارات: `nls.messages.json` المخبوز، و`package.nls.json` لكلّ
امتدادٍ مدمج، وملفّاتُ i18n لحزمة اللغة. استبدالٌ منسوخٌ ثلاثَ مرّاتٍ ينجرف بعد أوّل
تعديل. فالقاعدةُ هنا وحدَها، ونصُّها مُختبَرٌ في `tests/brand/check_brand.py`.

## ما يُستبدَل وما لا يُستبدَل — والفرقُ ليس تجميليًّا

**‏«VSCodium» يُستبدَل دائمًا** بلا استثناء: هو اسمُ التوزيعة التي بُني منها محراب،
ولا سياقَ يصحّ فيه أن يراه مستخدمُ محراب. كلُّ ظهورٍ له تسرّب.

**‏«VS Code» / «Visual Studio Code» يُستبدَلان مشروطَين**: أحيانًا هما إشارةٌ صادقةٌ
إلى طرفٍ ثالثٍ لا يملكه محراب — سوقُ الإضافات (ولا سوقَ لمحراب)، وقناةُ Insiders
(ولا قناةَ لمحراب)، ونسبةُ سمةٍ إلى صانعها («سمة ألوان Monokai لـ Visual Studio
Code»). استبدالُ هذه **كذبٌ** لا تعريب: يَعِد المستخدمَ بسوقٍ لا وجودَ له، وينسب
عملَ غيرِنا إلينا. فتُصان بقائمةٍ صريحةٍ ضيّقةٍ (`KEEP`) تُقرأ وتُراجَع، ويُستبدَل
ما عداها — وهو الأغلب، وكلُّه يتكلّم عن التطبيق الجاري نفسِه («أعد تشغيل VS Code»).

**المصانةُ حرفيًّا**: العناوينُ (‏https://…) والشيفرةُ بين شَولتين مائلتين والمُعوِّضات
‏(‏`${…}`، `{0}`). استبدالٌ داخلها يكسر رابطًا أو معرّفًا، لا يعرّبه.

اسمُ المنتج يُقرأ من `product-overrides/product.json` — المصدرُ نفسُه الذي يقرؤه
البناء، فلا سلسلةَ مكرَّرةٌ تنجرف عنه.
"""
import json
import os
import re

_HERE = os.path.dirname(os.path.abspath(__file__))
_OVERRIDES = os.path.join(os.path.dirname(_HERE), "product-overrides", "product.json")


def product_name(default="محراب"):
    """اسمُ المنتج الطويل من مصدر الهويّة الوحيد. الافتراضيُّ شبكةُ أمانٍ لا مصدرٌ ثانٍ."""
    try:
        with open(_OVERRIDES, "r", encoding="utf-8") as f:
            v = json.load(f).get("nameLong")
        return v if isinstance(v, str) and v else default
    except (OSError, ValueError):
        return default


NAME = product_name()

#: اسمُ توزيعتنا الأمّ. حسّاسٌ لحالة الأحرف جزئيًّا عمدًا: `(?i:vscodium)` يمسك
#: «vscodium» الصغيرةَ أيضًا (كانت تمرّ من كلّ الحرس)، بينما تبقى «Code OSS» على حالها
#: كي لا نلتقط كلمةَ «code» في نصٍّ تقنيٍّ عاديّ.
_ALWAYS = r"(?:(?i:vscodium)|Code ?- ?OSS|Code OSS)"

#: اسمُ الطرف الثالث الحقيقيّ. الأطولُ أوّلًا وإلّا ابتلع البديلُ القصيرُ جزءًا منه.
#: `\s*` لا ` ?`: «VS  Code» بفراغين كانت تمرّ بلا تطبيع (تسرّبٌ صامت).
_THIRD = r"(?:Visual Studio Code|VS\s*Code)"

#: أيُّ اسمِ منبعٍ كان — تستعمله أذرعُ الصَون التي يستوي فيها الاسمان (سوقٌ، معرض).
_ANY = r"(?:" + _ALWAYS + r"|" + _THIRD + r")"

#: مساحاتٌ لا يُلمَس ما بداخلها: عنوانٌ، أو شيفرةٌ بين شَولتين مائلتين (مفردةً أو
#: مزدوجة — المزدوجةُ أوّلًا وإلّا ابتلعت المفردةُ المحدِّدَين وتركت المتنَ مكشوفًا)،
#: أو مُعوِّضٌ، أو مسارٌ مطلقٌ بحرف قرصٍ أو UNC (اسمُ المجلّد لاتينيٌّ دائمًا: `Mihrab`).
_PROTECTED = (
    r"https?://\S+"
    r"|``[^\n]*?``"
    r"|`[^`\n]*`"
    r"|\$\{[^}\n]*\}"
    r"|\((?:command|cmd|vscode|file):[^)\n]*\)"
    # المسارُ يبتلع الفراغَ **فقط** إن بقي بعده فاصلُ مجلّداتٍ قبل الفراغ التالي —
    # كي يشمل «C:/Program Files/…» ولا يبتلع «C:/x ثمّ افتح VSCodium» فيُخفي تسرّبًا.
    r"|(?:[A-Za-z]:[\\/]|\\\\)(?:[^\s\"'\n]|\s(?=[^\s\"'\n]*[\\/]))*"
)

#: إشاراتٌ صادقةٌ إلى طرفٍ ثالثٍ — استبدالُها كذبٌ لا تعريب. تُصان كما هي.
#: كلُّ بندٍ هنا **دَينٌ معلَن**: يقول «هذه ميزةُ المنبع ولا نظيرَ لها في محراب».
#: والأذرعُ تقبل `_THIRD` كلَّه لا «Visual Studio Code» وحدَه: «سمة Monokai لـVS Code»
#: كانت تصير «لمحراب» فتنسب عملَ غيرِنا إلينا — وهو العطبُ الذي تحرّمه ديباجةُ الوحدة.
_KEEP = (
    # سوقُ الإضافات ومعرضُه: لا سوقَ لمحراب. يقبل الاسمين معًا وكلمةً فاصلةً بينهما.
    r"(?:معرض|سوق|متجر)\s*(?:إضافات\s*)?" + _ANY
    + r"|السوق\s+(?:في|لدى)\s*" + _ANY
    + r"|" + _ANY + r"\s*(?:Marketplace|Gallery)"
    # قنواتُ الإصدار وصِيَغُ منتجٍ لا نبنيها. الشَّرطةُ محتمَلة («VS Code - Insiders»).
    + r"|" + _THIRD + r"\s*[-–—]?\s*"
      r"(?:Insiders|Exploration|Server|Remote|Tunnel|Desktop|Web|CLI|for the Web|للويب|للوِب)"
    # ترتيبُ الصفة الإنجليزيّ (الوصفُ قبل الاسم) وترتيبُها العربيّ (بعده) معًا: العربيّةُ
    # تؤخّر الصفةَ، فذراعٌ تعرف الأوّلَ وحدَه لا تُمسِك الصياغةَ التي نكتبها نحن.
    + r"|(?:Insiders|المستقرّ?|التجريبيّ?)\s*(?:من\s+)?" + _THIRD
    + r"|" + _THIRD + r"\s*(?:التجريبيّ?|المستقرّ?|الاستكشافيّ?)"
    # تحديثٌ وحسابٌ ومزامنة: لا مُحدِّثَ في محراب (‏updateUrl=null) ولا مزوّدَ هويّة.
    + r"|(?:حدّث|تحديث|حساب|مزامنة)\s+" + _THIRD
    # نسبةُ سمةٍ إلى صانعها: «سمة ألوان Monokai لـVS Code» و«بسيط (Visual Studio Code)».
    + r"|لـ\s*" + _THIRD
    + r"|\(\s*" + _THIRD + r"\s*\)"
)

#: حرفُ جرٍّ يلتصق بالاسم اللاتينيّ بألفٍ خنجريّة: «لـVS Code» ⇐ «لمحراب» لا «لـمحراب».
#: **داخل المسحة لا بعدها**: تمريرةٌ لاحقةٌ على كامل النصّ كانت تُعيد كتابةَ «لـ محراب»
#: الواردةِ أصلًا في الجملة لمجرّد أنّ سلسلةً **أخرى** فيها استُبدلت — أثرٌ سياقيٌّ خفيّ.
_JARR = r"(?:(?P<jarr>[لبكف])ـ\s*)?"

#: **مسحةٌ واحدةٌ لا أقنعة.** البدائلُ مرتّبةٌ بالأسبقيّة، وpython يأخذ أوّلَ بديلٍ يطابق
#: في كلّ موضع: مصانٌ حرفيًّا ⟵ مصانٌ عمدًا ⟵ (حرفُ جرّ +) اسمُ منبعٍ يُستبدَل. والمسحةُ
#: الواحدةُ تُسقِط صنفَ عطبٍ كاملًا: لا مُعوِّضاتٍ نائبةً قد يحويها النصُّ المصدرُ نفسُه
#: فتنكسر عند الإرجاع، ولا اعتمادَ على ترتيب تمريراتٍ متتابعةٍ يسهل قلبُه سهوًا.
_SCAN = re.compile(
    "(?P<prot>" + _PROTECTED + ")"
    "|(?P<keep>" + _KEEP + ")"
    "|" + _JARR + "(?:(?P<always>" + _ALWAYS + ")|(?P<third>" + _THIRD + "))",
    re.UNICODE,
)

#: مسحةُ الجرد: ما نجا من اسم توزيعتنا الأمّ **خارج** المساحات المصانة حرفيًّا.
#: مستقلّةٌ عن `_SCAN` عمدًا: هناك تبتلع ذراعُ الصَون الاسمَ فلا يظهر، وهنا نريده أن
#: يظهر — «سوق VSCodium» تُصان من الاستبدال (لا نخترع لها سوقًا) وتُبلَّغ للإصلاح باليد.
_RESIDUE = re.compile(
    "(?P<prot>" + _PROTECTED + ")|(?P<name>" + _ALWAYS + ")", re.UNICODE)


def rebrand(text):
    """يعيد (النصّ بعد التطبيع، عددَ الاستبدالات). غيرُ النصّ يُعاد كما هو."""
    if not isinstance(text, str) or not text:
        return text, 0
    n = 0

    def sub(m):
        nonlocal n
        if m.group("always") is None and m.group("third") is None:
            return m.group(0)          # مصانٌ حرفيًّا أو مصانٌ عمدًا — يُعاد كما هو
        n += 1
        j = m.group("jarr")
        return (j + NAME) if j else NAME

    out = _SCAN.sub(sub, text)
    return (out, n) if n else (text, 0)


def rebrand_tree(obj):
    """يطبّع كلَّ نصٍّ في بنيةٍ متداخلة (قوائم/قواميس). يعيد (البنيةَ، عددَ الاستبدالات)."""
    if isinstance(obj, str):
        return rebrand(obj)
    if isinstance(obj, list):
        out, n = [], 0
        for v in obj:
            nv, k = rebrand_tree(v)
            out.append(nv)
            n += k
        return out, n
    if isinstance(obj, dict):
        out, n = {}, 0
        for key, v in obj.items():
            nv, k = rebrand_tree(v)
            out[key] = nv
            n += k
        return out, n
    return obj, 0


def leaks(text):
    """الإشاراتُ التي **يصونها** التطبيع عمدًا — للجرد لا للاستبدال.

    ليست عطبًا بل دَينٌ مُعلَن: تسميةُ ميزةٍ لا نظيرَ لها في محراب باسم صاحبها صدقٌ،
    وتسميتُها باسمنا كذب. طبعُها في تقرير الحرس يجعل الدَينَ مرئيًّا لا صامتًا.
    """
    if not isinstance(text, str) or not text:
        return []
    return [m.group("keep") for m in _SCAN.finditer(text) if m.group("keep") is not None]


#: ملفّاتُ **الأصل** التي نكتبها نحن لتكون مفصلَ التكرار (‏idempotency): منها نُعيد
#: البناءَ في كلّ مرور، فلو طُبِّعت ضاع الأصلُ وصار كلُّ بناءٍ يطبّع مطبَّعًا. تُستثنى من
#: المسح **بالاسم صراحةً** لا بإغفال المُطوِّر — والفرقُ أنّ الاستثناءَ المسمّى يُعَدُّ
#: ويُطبَع في التقرير، فيُرى ويُراجَع؛ والإغفالُ يُقرأ خُضرةً.
HINGE_NAMES = (
    "nls.messages.en.json",     # نسخةُ الإنجليزيّة الأصليّة (‏bake_nls_arabic)
    "nls.keys.json",            # مفاتيحُ لا نصٌّ مُصيَّر
    "package.nls.en.json",      # الاسمُ القديم — يُهاجَر عند البناء، ويُستثنى حتّى يزول
    ".mihrab-nls-orig.json",    # أصلُ بيانات كلّ امتدادٍ مدمج (خارجَ نمط package.nls.*)
)
HINGE_SUFFIXES = (".orig.json",)   # ‏*.i18n.orig.json و main.i18n.orig.json


def _values(obj):
    """كلُّ **قيمةٍ** نصّيّةٍ في بنيةٍ متداخلة — والمفاتيحُ لا تُمسّ عمدًا.

    قِيس في الحزمة: `main.i18n.json` يحوي `"VSCodium for Web": "{0} للويب"` — الاسمُ
    في **المفتاح**، وهو معرّفُ رسالةٍ إنجليزيٌّ لا يراه أحد، والقيمةُ عربيّةٌ نظيفة.
    فمسحٌ يقرأ المفاتيح يحمرّ على ما لا يُصيَّر، ويُعلَّم تجاهُلُه — وهو أسوأُ ما يصيب حارسًا.
    """
    if isinstance(obj, str):
        yield obj
    elif isinstance(obj, dict):
        for v in obj.values():
            yield from _values(v)
    elif isinstance(obj, list):
        for v in obj:
            yield from _values(v)


def scan_shipped(app, include_core=True):
    """يمسح **كلَّ** أسطح NLS في الحزمة المشحونة بحثًا عن اسم التوزيعة الأمّ.

    ## لماذا لا يكفي ما كان

    كان الحرسان ينظران إلى ملفَّين: `out/nls.messages.json` (مِجَسُّ L2) و
    `package.nls.json` لكلّ امتداد (بوّابةُ البناء). والحزمةُ تشحن **أكثرَ من ذلك**:
    ‏91 ملفَّ `package.nls.ar.json` و95 ملفَّ `*.i18n.json` — كُتبت تحصينًا لو سُجِّلت
    حزمةُ لغةٍ يومًا. وهي اليومَ مطبَّعةٌ صحيحةً، **ولا شيءَ يُثبت بقاءَها كذلك**: تعديلٌ
    يُسقِط التطبيعَ عن أحد المسارات يمرّ أخضرَ، لأنّ الحرسَ لا ينظر هناك.

    والسطحُ الخامدُ اليومَ حيٌّ غدًا بإعدادٍ واحد: `nls.language` يُسجِّل الحزمةَ فتُقرأ
    ملفّاتُ i18n بدل `package.nls.json`. فحمايةُ المسار المقروء وحدَه حمايةٌ بتاريخِ صلاحيّة.

    يعيد `(تسرّبات، إحصاء)`: الإحصاءُ `{اللاحقة: عددُ الملفّات}` للممسوح، ومفتاحٌ
    ‏`_hinges` لعدد المستثنى بالاسم. والصفرُ ليس نجاحًا — على القارئ أن يشترط شهودًا.
    """
    import json as _json

    found, stats = [], {"_hinges": 0}
    for root, _dirs, files in os.walk(app):
        for fname in files:
            if not fname.endswith(".json"):
                continue
            if "nls" not in fname and "i18n" not in fname:
                continue
            if fname in HINGE_NAMES or fname.endswith(HINGE_SUFFIXES):
                stats["_hinges"] += 1
                continue
            kind = ("i18n" if fname.endswith(".i18n.json")
                    else "nls.messages" if fname.startswith("nls.messages")
                    else fname if fname.startswith("package.nls") else "أخرى")
            # ‏`include_core=False`: نواةُ `out/nls.messages.json` **لم يأتِ دورُها بعد**.
            # يُستدعى هذا المسحُ مرّتين في البناء: مرّةً في (ط-0أ) حقنِ بيانات الامتدادات،
            # ومرّةً في (ي-2) بعد الخبز. والنواةُ يُعرّبها الخبزُ في (ط-0ب) — أي **بين
            # الاثنتين**. فمسحُها في الأولى يحاسب خطوةً لم تُشغَّل: على بناءٍ نظيفٍ تمامًا
            # يفشل البناءُ دائمًا، وعلى شجرةٍ مخبوزةٍ سلفًا ينجح — فيبدو الحارسُ سليمًا
            # لأنّه لا يُجرَّب إلّا في إعادة تشغيل. الترتيبُ لا يُعكَس (الخبزُ يبصم ملفّاتِ
            # i18n المحقونة قبلَه)، فتُفصَل المسؤوليّة: كلُّ بوّابةٍ تحاسب على سطحها.
            if not include_core and kind == "nls.messages":
                stats["_deferred_core"] = stats.get("_deferred_core", 0) + 1
                continue
            path = os.path.join(root, fname)
            try:
                with open(path, "r", encoding="utf-8") as f:
                    doc = _json.load(f)
            except (OSError, ValueError):
                continue
            stats[kind] = stats.get(kind, 0) + 1
            rel = os.path.relpath(path, app)
            for s in _values(doc):
                for r in residue(s):
                    found.append(f"{rel}: {r} — «{s[:60]}»")
    return found, stats


def residue(text):
    """ما نجا من اسم توزيعتنا الأمّ خارجَ المساحات المصانة حرفيًّا — **عطبٌ يُوقِف الشحن**.

    الفرقُ عن `leaks`: تلك دَينٌ مقبولٌ باسم طرفٍ ثالثٍ حقيقيّ، وهذه اسمُ البرنامج الذي
    بُني منه محراب — لا سياقَ يصحّ فيه أن يراه مستخدمُ محراب. وحين تصونه ذراعُ صَونٍ من
    الاستبدال (كـ«سوق VSCodium») يبقى هنا مرئيًّا: القرارُ فيه إعادةُ صياغةٍ بيد إنسان،
    لا خريطةُ استبدالٍ تخترع لنا سوقًا لا نملكه.
    """
    if not isinstance(text, str) or not text:
        return []
    return [m.group("name") for m in _RESIDUE.finditer(text) if m.group("name") is not None]
